def sign_in_interactive(db: Supabase) -> None:
    """First run on a PC: a small local page (http://127.0.0.1:8765) to sign in
    with the app's account. The password is sent only to Supabase; what stays
    on disk is the refresh token (.session.json)."""
    import webbrowser
    from http.server import BaseHTTPRequestHandler, HTTPServer
    from urllib.parse import parse_qs

    from .supa import AuthError

    class Handler(BaseHTTPRequestHandler):
        def _page(self, html: str) -> None:
            body = html.encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self) -> None:
            self._page(LINK_PAGE.format(error=""))

        def do_POST(self) -> None:
            form = parse_qs(self.rfile.read(int(self.headers.get("Content-Length", 0))).decode())
            email, password = form.get("email", [""])[0].strip(), form.get("password", [""])[0]
            signup = form.get("action", ["in"])[0] == "up"
            try:
                (db.sign_up if signup else db.sign_in)(email, password)
            except AuthError as e:
                msg = str(e)
                if "Sign-ups are closed" in msg or "Database error saving new user" in msg:
                    msg = "este correo no tiene permiso para crear una cuenta"
                elif "already registered" in msg:
                    msg = "ese correo ya tiene cuenta: tocá Entrar"
                elif "Invalid login" in msg:
                    msg = "el correo o la contraseña no coinciden"
                self._page(LINK_PAGE.format(error=f"No se pudo {'crear la cuenta' if signup else 'entrar'}: {msg}"))
                return
            self._page(LINK_PAGE.format(error="").split("<form")[0].replace("Vincular esta PC", "PC vinculada") + "<p>Listo, ya podés cerrar esta pestaña.</p></main></html>")

        def log_message(self, *args) -> None:
            pass

    server = HTTPServer(("127.0.0.1", LINK_PORT), Handler)
    url = f"http://127.0.0.1:{LINK_PORT}"
    log.info("not signed in yet: open %s to link this PC", url)
    try:
        webbrowser.open(url)
    except Exception:
        pass
    while not db.signed_in():
        server.handle_request()
    server.server_close()
    log.info("signed in")


class GpuBusy(Exception):
    """Not enough free VRAM to load a model next to what the desktop uses."""


def free_vram_mb() -> int | None:
    """Free VRAM without creating a CUDA context (that alone takes ~300 MB):
    nvidia-smi if present, else torch. None = unknown (no NVIDIA tools)."""
    try:
        import subprocess

        out = subprocess.run(["nvidia-smi", "--query-gpu=memory.free", "--format=csv,noheader,nounits"],
                             capture_output=True, text=True, timeout=10)
        if out.returncode == 0 and out.stdout.strip():
            return int(out.stdout.split()[0])
    except (OSError, ValueError, subprocess.SubprocessError):
        pass
    try:
        import torch

        if torch.cuda.is_available():
            return torch.cuda.mem_get_info()[0] // 2**20
    except Exception:
        pass
    return None


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def slug(voice: str) -> str:
    return "".join(c if c.isalnum() or c in "_-" else "_" for c in voice)


KOKORO_NAMES = {
    "ef_dora": "Dora", "em_alex": "Alex", "em_santa": "Santa", "af_heart": "Heart", "af_bella": "Bella",
    "af_nicole": "Nicole", "am_michael": "Michael", "am_fenrir": "Fenrir", "bf_emma": "Emma",
    "bm_george": "George", "bm_fable": "Fable",
}
CLONE_LABELS = {"ar_tomas": "Tomás", "ar_elena": "Elena", "en_andrew": "Andrew", "en_sonia": "Sonia"}


def available_voices() -> list[dict]:
    """What the app can offer: Kokoro's voices plus every reference clip in
    voices/ for each cloning engine (LatAm only for Spanish clips)."""
    voices = [{"id": f"kokoro:{v}", "label": KOKORO_NAMES.get(v, v), "languages": ["es"], "cloned": False} for v in KOKORO_ES]
    voices += [{"id": f"kokoro:{v}", "label": KOKORO_NAMES.get(v, v), "languages": ["en"], "cloned": False} for v in KOKORO_EN]
    for ref in sorted(VOICES_DIR.glob("*.wav")):
        name = ref.stem
        label = CLONE_LABELS.get(name, name.replace("_", " ").title())
        lang = "en" if name.startswith("en_") else "es"
        # Spanish clips go through the LatAm finetune only (better Spanish than the
        # general model, and one entry per voice keeps the app's list short).
        engine = "chatterbox-latam" if lang == "es" else "chatterbox-v3"
        voices.append({"id": f"{engine}:{name}", "label": label, "languages": [lang], "cloned": True})
    return voices


class Worker:
    def __init__(self) -> None:
        load_env()
        url, key = supabase_config()
        if not url or not key:
            sys.exit("Supabase is not configured yet (client/src/config.ts is empty). See CLAUDE.md.")
        self.db = Supabase(url, key, Path(os.environ.get("SESSION_FILE", ROOT / ".session.json")))
        if not self.db.signed_in():
            sign_in_interactive(self.db)
        self.work = Path(os.environ.get("WORK_DIR", ROOT / "work"))
        self.work.mkdir(parents=True, exist_ok=True)
        self.max_audio = int(os.environ.get("MAX_AUDIO_MB", "700")) * 1_000_000
        self.poll = float(os.environ.get("POLL_SECONDS", "15"))
        self.engine = None
        self.engine_voice: str | None = None
        self.asr = None
        self.last_beat = 0.0
        self.current: dict | None = None
        self.notice: str | None = None
        self.speed = Speed(self.work / "speed.json")
        # Local status for the Waybar module and its stop click (waybar.py).
        self.status_file = self.work / "status.json"
        self.stop_file = self.work / "stop-request"
        self.stop = False

    # ---- helpers ------------------------------------------------------------------
    def users(self) -> list[str]:
        return [self.db.user_id]

    def heartbeat(self, force: bool = False) -> None:
        if not force and time.time() - self.last_beat < 30:
            return
        self.last_beat = time.time()
        try:
            audio = self.db.select("narration_chapters", {"select": "user_id,bytes"})
            voices = available_voices()
            for uid in self.users():
                used = sum(r["bytes"] for r in audio if r["user_id"] == uid)
                self.db.upsert("worker_status", {"user_id": uid, "heartbeat": now_iso(), "voices": voices,
                                                 "current": self.current, "notice": self.notice,
                                                 "audio_bytes": used}, "user_id")
        except Exception as e:  # never die because of a heartbeat
            log.warning("heartbeat failed: %s", e)
        self.write_status()

    def write_status(self) -> None:
        state = {"state": "generating" if self.current else "blocked" if self.notice else "idle",
                 "current": self.current, "notice": self.notice, "at": time.time()}
        try:
            tmp = self.status_file.with_suffix(".tmp")
            tmp.write_text(json.dumps(state, ensure_ascii=False), encoding="utf-8")
            tmp.replace(self.status_file)
        except OSError:
            pass

    def unload(self) -> None:
        if self.engine is not None:
            self.engine.close()
            log.info("model unloaded")
        self.engine, self.engine_voice, self.asr = None, None, None
        free_gpu()

    def use_engine(self, voice: str):
        if self.engine_voice == voice:
            return self.engine
        engine_name, name = parse_voice(voice)
        if self.engine is not None and self.engine.info.name == engine_name:
            self.engine.set_voice(name)
        else:
            self.unload()
            free = free_vram_mb()
            need = VRAM_NEED_MB.get(engine_name, 3000) + VRAM_RESERVE_MB
            if free is not None and free < need:
                raise GpuBusy(f"la placa de video está ocupada: hacen falta {need} MB libres y hay {free} MB. "
                              "Cerrá algo que use la GPU y se reintenta solo")
            log.info("loading %s (%s MB of VRAM free)", engine_name, free)
            self.engine = load_engine(voice)
        self.engine_voice = voice
        if self.engine.info.needs_qc and self.asr is None:
            from .asr import Asr
            self.asr = Asr(os.environ.get("ASR_MODEL", "small"))
        return self.engine

    def manifest(self, book: dict) -> dict:
        cache = self.work / "manifests" / f"{book['id']}.json"
        if cache.exists():
            return json.loads(cache.read_text(encoding="utf-8"))
        m = self.db.download_json_gz("library", book["text_path"])
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_text(json.dumps(m, ensure_ascii=False), encoding="utf-8")
        return m

    def purge(self, book_id: str, voice: str | None = None, keep_voice: str | None = None) -> int:
        params = {"select": "voice,section,audio_path", "book_id": f"eq.{book_id}"}
        rows = self.db.select("narration_chapters", params)
        rows = [r for r in rows if (voice is None or r["voice"] == voice) and r["voice"] != keep_voice]
        if not rows:
            return 0
        self.db.remove("audio", [r["audio_path"] for r in rows])
        for r in rows:
            self.db.delete("narration_chapters", {"book_id": book_id, "voice": r["voice"], "section": str(r["section"])})
        shutil.rmtree(self.work / "chunks" / book_id, ignore_errors=True)
        return len(rows)

    # ---- sweep ----------------------------------------------------------------------
    def sweep_finished(self) -> None:
        # A day of grace: a book marked finished by mistake (on any device) keeps
        # its audio if it's switched back in time. All devices drop their local
        # copies when these chapters disappear (deleted_chapters).
        cutoff = datetime.fromtimestamp(time.time() - PURGE_AFTER_HOURS * 3600, timezone.utc).isoformat()
        finished = self.db.select("books", {"select": "id", "status": "eq.finished", "finished_at": f"lt.{cutoff}"})
        for b in finished:
            n = self.purge(b["id"])
            if n:
                log.info("book %s finished: removed %d audio chapters", b["id"], n)
            for row in self.db.select("narrations", {"select": "state", "book_id": f"eq.{b['id']}"}):
                if row["state"] != "purged":
                    self.db.update("narrations", {"book_id": b["id"]}, {"state": "purged", "current_section": None})

    def sweep_removed(self) -> None:
        # Books removed from the library ("Sacar de la biblioteca"): the app deletes
        # their rows and cloud files; only this PC's work files are left.
        leftovers = [p for d in ("chunks", "manifests") for p in (self.work / d).glob("*")]
        if not leftovers:
            return
        alive = {b["id"] for b in self.db.select("books", {"select": "id"})}
        for p in leftovers:
            if p.stem in alive:
                continue
            if p.is_dir():
                shutil.rmtree(p, ignore_errors=True)
            else:
                p.unlink(missing_ok=True)

    # ---- jobs --------------------------------------------------------------------------
    def next_job(self):
        rows = self.db.select("narrations", {"select": "*", "status": "eq.active", "order": "requested_at.asc"})
        for n in rows:
            if not runnable(n):
                continue
            books = self.db.select("books", {"select": "*", "id": f"eq.{n['book_id']}"})
            if not books or books[0]["status"] == "finished" or not books[0].get("text_path"):
                continue
            book = books[0]
            try:
                parse_voice(n["voice"])
            except ValueError as e:
                self.db.update("narrations", {"book_id": book["id"]}, {"state": "error", "error": str(e)})
                continue
            # Voice changed: the old audio goes (storage is tight).
            self.purge(book["id"], keep_voice=n["voice"])
            manifest = self.manifest(book)
            done = {r["section"] for r in self.db.select(
                "narration_chapters", {"select": "section", "book_id": f"eq.{book['id']}", "voice": f"eq.{n['voice']}"})}
            order = job_sections(manifest["sections"], n)
            pending = [s for s in order if s["i"] not in done]
            if not pending:
                if n["state"] != "ready":
                    self.db.update("narrations", {"book_id": book["id"]}, {"state": "ready", "current_section": None, "error": None})
                continue
            return book, n, manifest, pending, len(order) - len(pending), len(order)
        return None

    def space_left(self) -> bool:
        used = sum(r["bytes"] for r in self.db.select("narration_chapters", {"select": "bytes"}))
        return used < self.max_audio

    def stop_requested(self) -> bool:
        return self.stop_file.exists()

    def handle_stop_request(self) -> None:
        """Waybar click: stop what's running. Recorded as stopped_at (worker-owned)
        so it sticks until the user starts something again from the app."""
        try:
            self.stop_file.unlink()
        except OSError:
            return
        for n in self.db.select("narrations", {"select": "*", "status": "eq.active"}):
            if runnable(n):
                self.db.update("narrations", {"book_id": n["book_id"]}, {"stopped_at": now_iso(), "current_section": None})
        log.info("stopped from this PC")
        self.current = None
        self.unload()
        self.heartbeat(force=True)

    def generate(self, book: dict, n: dict, manifest: dict, pending: list[dict], done: int, total: int) -> None:
        section = pending[0]
        voice, lang = n["voice"], manifest.get("lang", "es")
        engine_name, _ = parse_voice(voice)
        if engine_name == "chatterbox-latam" and lang != "es":
            raise ValueError("la voz LatAm es solo para libros en español")
        if not self.space_left():
            raise RuntimeError("no queda espacio para audio en la nube: terminá o borrá otro libro con audio")
        engine = self.use_engine(voice)
        self.notice = None
        left = sum(chars(s) for s in pending)
        self.current = {"book_id": book["id"], "title": book["title"], "section": section["i"],
                        "label": section.get("label") or "", "voice": voice, "done": done, "total": total,
                        # When this job should end (epoch seconds), from the measured speed.
                        "until": round(time.time() + self.speed.eta(engine_name, left))}
        self.db.update("narrations", {"book_id": book["id"]}, {"state": "generating", "current_section": section["i"], "error": None})
        self.heartbeat(force=True)
        log.info("%s · section %d (%d/%d) · %s", book["title"], section["i"], done + 1, total, voice)

        sentences = [Sentence(text=s["t"], cfi=s["c"], block=s.get("b", 0), heading=bool(s.get("h"))) for s in section["sentences"]]
        cache = ChunkCache(self.work / "chunks" / book["id"] / slug(voice), str(section["i"]))
        last_check = [time.time()]

        def should_stop() -> bool:
            self.heartbeat()
            if self.stop or self.stop_requested():
                return True
            if time.time() - last_check[0] < 20:
                return False
            last_check[0] = time.time()
            row = self.db.select("narrations", {"select": "*", "book_id": f"eq.{book['id']}"})
            if not row or not runnable(row[0]) or row[0]["voice"] != voice or row[0]["started_at"] != n["started_at"]:
                return True
            p = row[0]["priority_section"]
            return p is not None and p != section["i"] and p != n.get("priority_section")

        t0 = time.time()
        audio = narrate(engine, sentences, lang, asr=self.asr if engine.info.needs_qc else None, cache=cache, should_stop=should_stop)
        if audio is None:
            log.info("switching: the user asked for something else")
            return
        out = self.work / "out" / f"{book['id']}-{slug(voice)}-{section['i']}.opus"
        write_opus(out, audio.wav, audio.sample_rate)
        data = out.read_bytes()
        path = f"{book['user_id']}/{book['id']}/{slug(voice)}/{section['i']}.opus"
        self.db.upload("audio", path, data, "audio/ogg")
        duration = audio.wav.size / audio.sample_rate
        try:
            self.db.upsert("narration_chapters", {
                "book_id": book["id"], "user_id": book["user_id"], "voice": voice, "section": section["i"],
                "audio_path": path, "duration": round(duration, 3), "bytes": len(data),
                "timings": [{"i": tm.index, "cfi": tm.cfi, "s": tm.start, "e": tm.end} for tm in audio.timings],
            }, "book_id,voice,section")
        except Exception:
            # Most likely the book was removed from the library meanwhile: don't
            # leave its audio in the cloud with no row pointing at it.
            self.db.remove("audio", [path])
            raise
        out.unlink(missing_ok=True)
        shutil.rmtree(self.work / "chunks" / book["id"] / slug(voice) / str(section["i"]), ignore_errors=True)
        for w in audio.warnings:
            log.warning(w)
        took = time.time() - t0
        self.speed.record(engine_name, chars(section), took)
        log.info("  done: %.1f min of audio in %.1f min (%.1fx), %.1f MB", duration / 60, took / 60, duration / max(took, 1e-6), len(data) / 1e6)
        # The next loop marks the job ready when nothing of it is left.
        self.db.update("narrations", {"book_id": book["id"]}, {"current_section": None})

    # ---- main loop ------------------------------------------------------------------------
    def run(self) -> None:
        log.info("worker started · engines: %s · voices dir: %s", ", ".join(ENGINES), VOICES_DIR)
        signal.signal(signal.SIGINT, lambda *_: setattr(self, "stop", True))
        signal.signal(signal.SIGTERM, lambda *_: setattr(self, "stop", True))
        self.stop_file.unlink(missing_ok=True)  # a click from before this start doesn't count
        oom = 0
        while not self.stop:
            try:
                if self.stop_requested():
                    self.handle_stop_request()
                self.heartbeat()
                self.sweep_finished()
                self.sweep_removed()
                job = self.next_job()
                if job:
                    book, n, *_ = job
                    try:
                        self.generate(*job)
                        oom = 0
                        continue
                    except GpuBusy as e:
                        # Never thrash: say why in the app and Waybar, wait, retry.
                        log.warning("%s", e)
                        self.notice, self.current = str(e), None
                        self.heartbeat(force=True)
                    except Exception as e:
                        if type(e).__name__ == "OutOfMemoryError":
                            # Fragmented or crowded VRAM: retrying with the same process
                            # state fails forever (happened 2026-10-22, 3 h lost). Reload
                            # the model from scratch; finished chunks are on disk.
                            oom += 1
                            log.warning("GPU out of memory (%d in a row): reloading the model", oom)
                            self.unload()
                            self.current = None
                            self.heartbeat(force=True)
                            self.wait(min(300, 30 * oom))
                            continue
                        log.exception("generation failed")
                        self.db.update("narrations", {"book_id": book["id"]}, {"state": "error", "error": str(e)[:300]})
                else:
                    self.go_idle()
            except Exception as e:
                log.warning("loop error (retrying): %s", e)
            self.wait(self.poll)
        log.info("stopped")

    def go_idle(self) -> None:
        """Nothing to do: free the GPU completely. Unloading the model leaves
        PyTorch's CUDA context (~300 MB) behind, so the process restarts itself
        once it has touched CUDA (Linux; on Windows a model unload is enough)."""
        busy = self.current is not None or self.notice is not None
        self.current, self.notice = None, None
        if busy:
            self.heartbeat(force=True)
        if self.engine is None and "torch" not in sys.modules:
            return
        self.unload()
        if os.name == "posix" and "torch" in sys.modules:
            import torch

            if torch.cuda.is_initialized():
                log.info("idle: restarting to release the GPU")
                logging.shutdown()
                os.execv(sys.executable, [sys.executable, "-m", "worker"])

    def wait(self, seconds: float) -> None:
        for _ in range(int(seconds * 2)):
            if self.stop or self.stop_requested():
                break
            time.sleep(0.5)


