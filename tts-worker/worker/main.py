"""The narration worker: watches Supabase and turns books into audio, one
chapter at a time, on this PC's GPU.

    uv run python -m worker            (or ./run.sh / run.bat)

Nothing is generated by itself: a job exists only because the user started
it from the desktop app ("Generar ahora": this chapter, the next 3 or the whole
book) and it runs until it's done or someone taps "Parar" (app, phone, or the
Waybar module on this PC). See worker/jobs.py.

Loop:
  1. Heartbeat: worker_status (voices available, what it's doing, ETA,
     a notice when the GPU has no room).
  2. Sweep: finished books lose their audio in Storage (regenerable later).
  3. Job: the oldest runnable narration with chapters of its job still missing.
  4. VRAM guard, then synthesize → Opus → upload → narration_chapters row.
  5. Nothing left: unload the model and, if CUDA was touched, restart the
     process so no GPU memory at all stays taken while idle.

Resumable: a chapter is done only when its row exists; inside a chapter every
chunk is cached on disk (work/chunks), so after a power cut it picks up the
same chapter where it stopped. While a chapter is being generated the worker
checks every ~20 s whether the user asked for a different one, and switches.
"""

